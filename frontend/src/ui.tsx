import type { ReactNode } from 'react'

export const SERIES = ['var(--s1)', 'var(--s2)', 'var(--s3)', 'var(--s4)', 'var(--s5)', 'var(--s6)', 'var(--s7)']
export const HEX = ['#3987e5', '#d95926', '#199e70', '#c98500', '#d55181', '#008300', '#9085e9']
export const AXIS = { stroke: '#8c99a4', fontSize: 11, tickLine: false, axisLine: false } as const
export const GRID = { stroke: '#243039', strokeDasharray: '0', vertical: false } as const

export const eur = (n: number | null | undefined, d = 0) =>
  n == null ? '—' : (n < 0 ? '−€' : '€') + Math.abs(n).toLocaleString('en-GB', { minimumFractionDigits: d, maximumFractionDigits: d })
export const pct = (n: number | null | undefined, d = 0) => (n == null ? '—' : (n * 100).toFixed(d) + '%')
export const int = (n: number | null | undefined) => (n == null ? '—' : Math.round(n).toLocaleString('en-GB'))
export const mmss = (s: number | null | undefined) => (s == null ? '—' : `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`)
export const DOW = ['', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

export function Source({ kind }: { kind: 'real' | 'sim' | 'llm' }) {
  const label = { real: 'Real H&M data', sim: 'Simulated', llm: 'Generated by LLM' }[kind]
  return <span className={`badge ${kind}`}>{label}</span>
}

export function Card({ title, sub, source, right, children }: { title: string; sub?: string; source?: 'real' | 'sim' | 'llm'; right?: ReactNode; children: ReactNode }) {
  return (
    <section className="card">
      <div className="card-head">
        <div>
          <h3>{title}</h3>
          {sub && <p className="sub">{sub}</p>}
        </div>
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>{right}{source && <Source kind={source} />}</div>
      </div>
      {children}
    </section>
  )
}

export function Kpi({ label, value, hint }: { label: string; value: ReactNode; hint?: string }) {
  return (
    <div className="kpi">
      <span>{label}</span>
      <b>{value}</b>
      {hint && <small>{hint}</small>}
    </div>
  )
}

type TTItem = { name?: string | number; value?: number | string; color?: string; payload?: Record<string, unknown> }
export function Tip({ active, payload, label, fmt, labelFmt }: { active?: boolean; payload?: TTItem[]; label?: string | number; fmt?: (v: number, name: string) => string; labelFmt?: (l: string | number) => string }) {
  if (!active || !payload?.length) return null
  return (
    <div className="tt">
      <div style={{ color: 'var(--muted)', marginBottom: 4 }}>{labelFmt ? labelFmt(label ?? '') : label}</div>
      {payload.map((p, i) => (
        <div className="row" key={i}>
          <span className="sw" style={{ background: p.color }} />
          <span>{p.name}</span>
          <b style={{ marginLeft: 'auto', paddingLeft: 12 }}>{fmt ? fmt(Number(p.value), String(p.name)) : String(p.value)}</b>
        </div>
      ))}
    </div>
  )
}

export function Toggle<T extends string>({ options, value, onChange, labels }: { options: readonly T[] | T[]; value: T; onChange: (v: T) => void; labels?: Partial<Record<T, string>> }) {
  return (
    <div className="tabs-inline" role="group">
      {options.map(o => (
        <button key={o} type="button" aria-pressed={o === value} onClick={() => onChange(o)}>{labels?.[o] ?? o}</button>
      ))}
    </div>
  )
}

export function BarCell({ value, max, label, color = 'var(--s1)' }: { value: number; max: number; label: string; color?: string }) {
  return (
    <div className="bar-cell">
      <span className="b" style={{ width: `${Math.max(2, (value / (max || 1)) * 90)}px`, background: color }} />
      <span className="num">{label}</span>
    </div>
  )
}

export const Empty = ({ children }: { children: ReactNode }) => <div className="empty">{children}</div>
